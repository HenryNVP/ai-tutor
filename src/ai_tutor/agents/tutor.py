    def _parse_routing_response(self, text: str) -> Optional[RoutingDecision]:
        if not text:
            return None
        try:
            start = text.index("{")
            end = text.rindex("}") + 1
            payload = json.loads(text[start:end])
        except (ValueError, json.JSONDecodeError):
            logger.debug("[TutorAgent] Unable to parse routing JSON: %s", text)
            return None

        route = str(payload.get("route", "qa")).strip().lower()
        if route not in {"qa", "note", "quiz", "web", "ingestion"}:
            route = "qa"

        reason = str(payload.get("reason") or "LLM routing fallback")
        source_mentions_raw = payload.get("source_mentions") or []
        source_mentions = [
            str(item).strip()
            for item in source_mentions_raw
            if isinstance(item, str) and item.strip()
        ] or None

        quiz_topic = payload.get("quiz_topic")
        if isinstance(quiz_topic, str):
            quiz_topic = quiz_topic.strip()
        else:
            quiz_topic = None
        quiz_count = payload.get("quiz_count")
        try:
            quiz_count_int = int(quiz_count) if quiz_count is not None else None
        except (TypeError, ValueError):
            quiz_count_int = None

        confidence = payload.get("confidence")
        try:
            confidence_value = float(confidence)
        except (TypeError, ValueError):
            confidence_value = 0.5

        return RoutingDecision(
            target=route,  # type: ignore[arg-type]
            reason=reason,
            source_filter=source_mentions,
            quiz_topic=quiz_topic or None,
            quiz_count=quiz_count_int,
            deterministic=False,
            confidence=confidence_value,
        )

    def _apply_document_hints(
        self,
        decision: RoutingDecision,
        question: str,
        extra_context: Optional[str],
        source_hints: Optional[List[str]],
    ) -> RoutingDecision:
        hints: List[str] = []
        if source_hints:
            hints.extend([hint for hint in source_hints if hint])
        if extra_context:
            context_refs = extract_source_mentions(extra_context)
            hints.extend([ref for ref in context_refs if ref not in hints])
        if decision.source_filter:
            hints.extend([ref for ref in decision.source_filter if ref not in hints])

        doc_request = detect_document_request(question, hints or None)
        if doc_request.source_filter:
            merged = decision.source_filter[:] if decision.source_filter else []
            for ref in doc_request.source_filter:
                if ref not in merged:
                    merged.append(ref)
            decision.source_filter = merged
        decision.documents_only = doc_request.use_documents_only or decision.documents_only
        return decision

