@dataclass
class TutorResponse:
    """
    Structured response container for tutor interactions.
    
    This dataclass encapsulates all information returned from a tutoring session,
    including the generated answer, retrieval evidence, personalization hints,
    and optional quiz payloads.
    
    Attributes
    ----------
    answer : str
        The generated response text from the tutor agent. May include citation
        markers like [1], [2] that correspond to the citations list.
    hits : List[RetrievalHit]
        Raw retrieval results from the vector store, containing chunks and similarity
        scores. Empty for web-sourced or quiz-only responses.
    citations : List[str]
        Formatted citation strings (e.g., "[1] Title (Doc: id, Page: 42)") that
        map to bracketed indices in the answer text. Empty if no local sources used.
    style : str
        The explanation style used for this response. One of "scaffolded" (detailed,
        step-by-step), "stepwise" (moderate guidance), or "concise" (advanced).
    next_topic : Optional[str]
        Suggested next topic for the learner based on their current progress and
        knowledge gaps. None if not applicable.
    difficulty : Optional[str]
        Current difficulty level label for the learner in this domain. One of
        "foundational guidance", "guided practice", or "independent challenge".
    source : Optional[str]
        Origin of the answer. One of "local" (RAG from course materials), "web"
        (internet search), "quiz" (assessment generation), or None.
    quiz : Optional[Quiz]
        Generated quiz object if the interaction produced an assessment. Contains
        questions, correct answers, and explanations.
    """

    answer: str
    hits: List[RetrievalHit]
    citations: List[str]
    style: str
    next_topic: Optional[str] = None
    difficulty: Optional[str] = None
    source: Optional[str] = None
    quiz: Optional[Quiz] = None
    route: str = "qa"
    saved_file_path: Optional[str] = None  # Path to file saved by note agent
    visualization: Optional[Dict[str, Any]] = None  # Visualization result from visualization agent


@dataclass
class AgentState:
    """
    Shared state object for multi-agent communication.
    
    This mutable state container allows specialist agents (QA, Web, Quiz) to
    store their results, which the orchestrator then collects and formats into
    a unified TutorResponse. The state is reset at the start of each new query.
    
    Attributes
    ----------
    last_hits : List[RetrievalHit]
        Retrieval results from the most recent vector search. Used by QA agent
        to pass evidence back to orchestrator.
    last_citations : List[str]
        Formatted citation strings generated by specialist agents. Collected
        and attached to the final response.
    last_source : Optional[str]
        Identifier for the agent that handled the last query ("local", "web", etc.).
        Helps orchestrator determine response formatting.
    last_quiz : Optional[Quiz]
        Quiz object generated by the quiz tool. If present, the response includes
        interactive assessment UI.
    """
    
    last_hits: List[RetrievalHit] = field(default_factory=list)
    last_citations: List[str] = field(default_factory=list)
    last_source: Optional[str] = None
    last_quiz: Optional[Quiz] = None
    last_visualization: Optional[Dict[str, Any]] = None

    def reset(self) -> None:
        """
        Clear all state variables to prepare for a new query.
        
        Called at the start of each answer() invocation to ensure agents don't
        carry over results from previous interactions.
        """
        self.last_hits.clear()
        self.last_citations.clear()
        self.last_source = None
        self.last_quiz = None
        self.last_visualization = None


class TutorAgent:
    """
    Multi-agent tutoring coordinator using the OpenAI Agents SDK.
    
    This class implements an agent-first architecture with a thin router that
    applies deterministic rules (document references, quizzes, ingestion, news)
    before delegating to specialist agents. When heuristics are inconclusive,
    a lightweight routing agent produces structured JSON to guide delegation.
    
    Supported capabilities:
    - STEM Q&A with retrieval-augmented generation (qa_agent)
    - Current events and web searches (web_agent)
    - Document ingestion and corpus management (ingestion_agent)
    - Summaries and note files (note_agent)
    - Quiz generation/evaluation (quiz_agent + QuizService)
    
    Conversation context is maintained via SQLite sessions that rotate
    automatically to prevent prompt bloat. Specialist results are stored in
    AgentState and formatted into TutorResponse objects.
    
    Attributes
    ----------
    MIN_CONFIDENCE : float
        Minimum similarity score (0.2) for retrieval results to be considered
        relevant. Queries with no hits above this threshold fall back to web search.
    retriever : Retriever
        Vector search coordinator that embeds queries and retrieves similar chunks.
    # Web search is handled directly by web_agent using WebSearchTool
    ingest_fn : Callable
        Directory ingestion function for processing and indexing new documents.
    sessions : Dict[str, SQLiteSession]
        In-memory cache of active conversation sessions, keyed by learner_id.
    state : AgentState
        Shared mutable state for inter-agent communication.
    session_db_path : Path
        SQLite database path for persistent conversation history.
    quiz_service : QuizService
        Assessment generator that creates and evaluates quizzes.
    """

    MIN_CONFIDENCE = 0.2  # Minimum retrieval score for accepting local results
    MIN_ROUTING_CONFIDENCE = 0.45  # Below this, fall back to QA for safety

    def __init__(
        self,
        retrieval_config: RetrievalConfig,
        embedder: EmbeddingClient,
        vector_store: VectorStore,
        ingest_directory: Callable[[Path], object],
        session_db_path: Path,
        quiz_service: QuizService,
        mcp_servers: Optional[Dict[str, Any]] = None,
    ):
        """
        Initialize the multi-agent system with all required dependencies.
        
        Parameters
        ----------
        retrieval_config : RetrievalConfig
            Configuration for vector search (top_k, thresholds, etc.).
        embedder : EmbeddingClient
            Sentence transformer for encoding queries and documents.
        vector_store : VectorStore
            Indexed vector database for similarity search.
        # Web search handled directly by web_agent
        ingest_directory : Callable[[Path], object]
            Function to process and index documents from a directory.
        session_db_path : Path
            SQLite database path for conversation persistence.
        quiz_service : QuizService
            Service for generating and evaluating assessments.
        """
        # Core retrieval infrastructure
        self.retriever = Retriever(retrieval_config, embedder=embedder, vector_store=vector_store)
        self.ingest_fn = ingest_directory
        self.mcp_servers = mcp_servers or {}
        self.mcp_server = self.mcp_servers.get("chroma") or next(iter(self.mcp_servers.values()), None)
        self._filesystem_mcp = (
            self.mcp_servers.get("filesystem")
            or next((server for name, server in self.mcp_servers.items() if "filesystem" in name.lower()), None)
        )
        
        if self.mcp_servers:
            server_names = ", ".join(self.mcp_servers.keys())
            logger.info("[TutorAgent] MCP servers provided (%s) - agents will use MCP tools with cached lists", server_names)
        
        # Session and state management
        self.sessions: Dict[str, SQLiteSession] = {}  # Learner ID → Active session
        self.session_turn_counts: Dict[str, int] = {}  # Track turns per session for pruning
        self.state = AgentState()  # Shared state for agent communication
        self.session_db_path = session_db_path
        self.max_turns_per_session = 3  # Prune history: create new session after 3 turns
        
        # Quiz and assessment infrastructure
        self.quiz_service = quiz_service
        
        # Temporary context for quiz generation (set during answer() calls)
        self._active_profile: Optional[LearnerProfile] = None
        self._active_extra_context: Optional[str] = None
        self._active_source_filter: Optional[List[str]] = None
        self._documents_only_request: bool = False

        # Agent instances (initialized in _build_agents)
        self.ingestion_agent: Agent | None = None
        self.qa_agent: Agent | None = None
        self.note_agent: Agent | None = None
        self.web_agent: Agent | None = None
        self.quiz_agent: Agent | None = None
        self.visualization_agent: Agent | None = None
        self.routing_agent: Agent | None = None
        self._routing_session: SQLiteSession | None = None

        self._build_agents()

    def _build_agents(self) -> None:
        """
        Construct the specialist agents for the agent-first architecture.
        
        Each agent owns a single responsibility:
        - ingestion_agent: handles new document ingestion
        - qa_agent: retrieval-augmented Q&A
        - note_agent: summaries and note files
        - web_agent: current events via web search
        - quiz_agent: quiz generation via QuizService
        - routing_agent: LLM fallback router that emits structured JSON
        """
        logger.debug("[TutorAgent] Building specialist agents with persistent MCP context")
        self.ingestion_agent = build_ingestion_agent(self.ingest_fn)
        self.web_agent = build_web_agent(state=self.state)
        self.qa_agent = build_qa_agent(
            self.retriever, 
            self.state, 
            self.MIN_CONFIDENCE, 
            mcp_servers=list(self.mcp_servers.values()),  # Pass persistent MCP connections (tools cached per session)
            mcp_server_names=list(self.mcp_servers.keys()),  # Pass server names for proper detection
        )
        self.note_agent = build_note_agent(
            self.retriever,
            self.state,
            self.MIN_CONFIDENCE,
            mcp_servers=list(self.mcp_servers.values()),
            mcp_server_names=list(self.mcp_servers.keys()),
        )
        self.quiz_agent = build_quiz_agent(
            self.quiz_service,
            self.state,
            get_profile=lambda: self._active_profile,
            get_extra_context=lambda: self._active_extra_context,
            get_source_filter=lambda: self._active_source_filter,
            get_documents_only=lambda: self._documents_only_request,
        )
        self.visualization_agent = build_visualization_agent(
            state=self.state,
        )
        if self.mcp_servers:
            logger.info("[TutorAgent] Agents built with MCP tool access (%d server(s))", len(self.mcp_servers))
        else:
            logger.info("[TutorAgent] Agents built without MCP servers (direct vector store access)")
        routing_instructions = (
            "You are the routing agent. You must decide which specialist agent should handle a learner request.\n"
            "- Valid routes: qa, note, quiz, web, ingestion, visualization.\n"
            "- Respond ONLY with compact JSON: "
            '{"route": "...", "reason": "...", "source_mentions": [], "quiz_topic": null, "quiz_count": null, "confidence": 0-1}.\n'
            "- Prefer deterministic rules: quizzes/tests -> quiz, summaries/notes/text-file creation/saving -> note, news/current events -> web, ingestion/upload/indexing of learner documents -> ingestion, "
            "plot/chart/graph/visualize requests -> visualization, otherwise default to qa.\n"
            "- Preserve exact document titles or filenames in source_mentions; never use placeholders like 'uploaded documents'.\n"
            "- If unsure, pick the most likely route but lower confidence."
        )
        self.routing_agent = Agent(
            name="routing_agent",
            model="gpt-4o-mini",
            instructions=routing_instructions,
        )
        self._routing_session = SQLiteSession(
            "ai_tutor_router",
            db_path=str(self.session_db_path),
        )


    def evaluate_quiz(
        self,
        *,
        quiz: Quiz,
        answers: List[int],
        profile: Optional[LearnerProfile],
    ) -> QuizEvaluation:
        """Score a learner's quiz submission and return detailed feedback."""
        return self.quiz_service.evaluate_quiz(
            quiz=quiz,
            answers=answers,
            profile=profile,
        )

    def answer(
        self,
        learner_id: str,
        question: str,
        mode: str,
        style_hint: str,
        profile: Optional[LearnerProfile] = None,
        extra_context: Optional[str] = None,
        source_hints: Optional[List[str]] = None,
        on_delta: Optional[Callable[[str], None]] = None,
    ) -> TutorResponse:
        """Synchronously orchestrate the multi-agent run and produce a TutorResponse."""
        try:
            # Check if we're already in an event loop
            asyncio.get_running_loop()
            # If we're in a loop, raise an error suggesting to use answer_async instead
            raise RuntimeError(
                "Cannot call answer() from within an async context. "
                "Use answer_async() instead or call from a sync context."
            )
        except RuntimeError as e:
            if "Cannot call answer()" in str(e):
                raise
            # No running loop, safe to use asyncio.run()
        return asyncio.run(
            self._answer_async(
                learner_id=learner_id,
                question=question,
                mode=mode,
                style_hint=style_hint,
                profile=profile,
                extra_context=extra_context,
                    source_hints=source_hints,
                on_delta=on_delta,
            )
            )
    
    async def answer_async(
        self,
        learner_id: str,
        question: str,
        mode: str,
        style_hint: str,
        profile: Optional[LearnerProfile] = None,
        extra_context: Optional[str] = None,
        source_hints: Optional[List[str]] = None,
        on_delta: Optional[Callable[[str], None]] = None,
    ) -> TutorResponse:
        """Asynchronously orchestrate the multi-agent run and produce a TutorResponse."""
        return await self._answer_async(
            learner_id=learner_id,
            question=question,
            mode=mode,
            style_hint=style_hint,
            profile=profile,
            extra_context=extra_context,
            source_hints=source_hints,
            on_delta=on_delta,
        )

    async def _answer_async(
        self,
        learner_id: str,
        question: str,
        mode: str,
        style_hint: str,
        profile: Optional[LearnerProfile],
        extra_context: Optional[str],
        source_hints: Optional[List[str]],
        on_delta: Optional[Callable[[str], None]],
    ) -> TutorResponse:
        import time

        answer_start = time.time()
        logger.info("[TutorAgent] Starting answer generation for learner=%s", learner_id)

        current_turn = self.session_turn_counts.get(learner_id, 0)
        if current_turn > 0 and current_turn % self.max_turns_per_session == 0:
            logger.info(
                "[TutorAgent] Pruning history for %s after %s turns",
                learner_id,
                current_turn,
            )
            if learner_id in self.sessions:
                del self.sessions[learner_id]

        session = self._get_session(learner_id)
        self.state.reset()
        self.session_turn_counts[learner_id] = current_turn + 1

        decision = await self._route_question(
            question=question,
            extra_context=extra_context,
            source_hints=source_hints,
            profile=profile,
        )
        logger.info(
            "[TutorAgent] Routing decision: route=%s reason=%s deterministic=%s source_filter=%s",
            decision.target,
            decision.reason,
            decision.deterministic,
            decision.source_filter,
        )

        if not decision.source_filter and should_use_source_filter(question):
            decision.source_filter = extract_source_mentions(question)

        if decision.target == "quiz":
            # Use extract_quiz_topic if topic wasn't set by routing, passing context for better extraction
            if not decision.quiz_topic:
                from ai_tutor.learning.quiz_intent import extract_quiz_topic
                decision.quiz_topic = extract_quiz_topic(
                    question,
                    extra_context=extra_context,
                    source_filter=decision.source_filter or source_hints,
                )
            decision.quiz_count = decision.quiz_count or self._infer_count_from_request(question)

        prompt = self._build_agent_prompt(
            question=question,
            mode=mode,
            style_hint=style_hint,
            profile=profile,
            extra_context=extra_context,
            decision=decision,
        )

        self._active_profile = profile
        self._active_extra_context = extra_context
        self._active_source_filter = decision.source_filter
        self._documents_only_request = decision.documents_only
        self.state.last_quiz = None
        try:
            answer_text, quiz_payload = await self._execute_decision(
                decision=decision,
                prompt=prompt,
                session=session,
                on_delta=on_delta,
            )
        finally:
            self._active_profile = None
            self._active_extra_context = None
            self._active_source_filter = None
            self._documents_only_request = False

        if quiz_payload is None and self.state.last_quiz is not None:
            quiz_payload = self.state.last_quiz

        # If routing missed a quiz request, re-route through quiz agent
        # This ensures all quiz generation goes through the quiz_agent for consistency
        if quiz_payload is None and self._should_force_quiz(question) and decision.target != "quiz":
            logger.info(
                "[TutorAgent] Quiz request detected but missed by routing. Re-routing through quiz agent."
            )
            # Use extract_quiz_topic with context for better topic extraction
            from ai_tutor.learning.quiz_intent import extract_quiz_topic
            fallback_topic = extract_quiz_topic(
                question,
                extra_context=extra_context,
                source_filter=decision.source_filter or source_hints,
            )
            # Create a proper routing decision for quiz
            quiz_decision = RoutingDecision(
                target="quiz",
                reason="Fallback: detected quiz intent keywords",
                quiz_topic=fallback_topic,
                quiz_count=self._infer_count_from_request(question),
                deterministic=False,
                confidence=0.8,
            )
            # Build prompt for quiz agent
            quiz_prompt = self._build_agent_prompt(
                question=question,
                mode=mode,
                style_hint=style_hint,
                profile=profile,
                extra_context=extra_context,
                decision=quiz_decision,
            )
            # Execute through quiz agent
            self._active_profile = profile
            self._active_extra_context = extra_context
            try:
                answer_text, _ = await self._execute_decision(
                    decision=quiz_decision,
                    prompt=quiz_prompt,
                    session=session,
                    on_delta=on_delta,
                )
            finally:
                self._active_profile = None
                self._active_extra_context = None
            # Check if quiz was generated
            if self.state.last_quiz is not None:
                quiz_payload = self.state.last_quiz

        saved_file_path = None
        if decision.target == "note":
            # Check if note agent already saved a file (stored in state)
            saved_file_path = getattr(self.state, 'saved_file_path', None)
            # Also try explicit file creation if requested (for explicit "create file" requests)
            if not saved_file_path and answer_text:
                saved_file_path = await self._maybe_write_text_file(question, answer_text)
            # Clear saved_file_path from state after use
            if hasattr(self.state, 'saved_file_path'):
                delattr(self.state, 'saved_file_path')

        if quiz_payload is None and not self.state.last_citations:
            answer_text = self._strip_citation_markers(answer_text)

        hits = self.state.last_hits if not quiz_payload else []
        citations = self.state.last_citations if not quiz_payload else []

        if decision.target == "quiz":
            source = "quiz"
        elif decision.target == "web":
            source = "web"
        elif decision.target == "note":
            source = "notes"
        elif decision.target == "ingestion":
            source = "ingestion"
        elif decision.target == "visualization":
            source = "visualization"
        else:
            source = self.state.last_source

        total_answer_duration = time.time() - answer_start
        logger.info("[TutorAgent] Answer generation complete in %.2fs", total_answer_duration)

        if saved_file_path:
            note_suffix = f"\n\n_(Saved to {saved_file_path})_"
            if note_suffix not in answer_text:
                answer_text = f"{answer_text}{note_suffix}"

        # Get visualization result from state if available
        visualization_result = self.state.last_visualization

        return TutorResponse(
            answer=answer_text,
            hits=hits,
            citations=citations,
            style=style_hint,
            source=source,
            quiz=quiz_payload,
            route=decision.target,
            saved_file_path=saved_file_path,  # Include saved file path in response
            visualization=visualization_result,  # Include visualization result
        )

    async def _maybe_write_text_file(self, question: str, content: str) -> Optional[str]:
        """Persist note content via filesystem MCP when explicitly requested."""
        if not self._filesystem_mcp:
            return None
        if not self._needs_text_file(question):
            return None
        filename = self._generate_note_filename(question)
        path = f"data/generated/text/{filename}.txt"
        try:
            result = await self._filesystem_mcp.call_tool(
                "write_text_file",
                {"path": path, "content": content, "overwrite": False},
            )
        except Exception as exc:
            logger.warning(
                "[TutorAgent] Failed to write note file via filesystem MCP: %s",
                exc,
                exc_info=True,
            )
            return None
        try:
            # Result content is JSON string per filesystem MCP contract
            text_payload = result.structuredContent.get("result") if result.structuredContent else None
            if not text_payload and result.content:
                text_payload = result.content[0].text
            if not text_payload:
                return path
            data = json.loads(text_payload)
            return data.get("path", path)
        except Exception:
            return path

    @staticmethod
    def _needs_text_file(question: str) -> bool:
        lowered = question.lower()
        keywords = [
            "create a text file",
            "write a text file",
            "make a text file",
            "draft a text file",
            "save this as a text file",
            "create file",
            "write file",
        ]
        return any(keyword in lowered for keyword in keywords)

    @staticmethod
    def _generate_note_filename(question: str) -> str:
        import re

        lowered = question.lower()
        # Try to capture topic after "introducing", "about", etc.
        match = re.search(r"(?:introducing|about|on)\s+([a-z0-9 \-_/]+)", lowered)
        if match:
            candidate = match.group(1)
        else:
            candidate = lowered
        slug = re.sub(r"[^a-z0-9]+", "-", candidate).strip("-")
        slug = slug or "note"
        if len(slug) > 60:
            slug = slug[:60].rstrip("-")
        return slug or "note"

    async def _route_question(
        self,
        question: str,
        extra_context: Optional[str],
        source_hints: Optional[List[str]],
        profile: Optional[LearnerProfile],
    ) -> RoutingDecision:
        decision = apply_deterministic_routing(question, extra_context=extra_context, source_filter=source_hints)
        if decision:
            return self._apply_document_hints(decision, question, extra_context, source_hints)
        routed = await self._route_with_llm(question, extra_context, profile)
        if (
            not routed.deterministic
            and routed.confidence is not None
            and routed.confidence < self.MIN_ROUTING_CONFIDENCE
        ):
            logger.warning(
                "[TutorAgent] Low-confidence routing decision (route=%s, confidence=%.2f). Falling back to QA.",
                routed.target,
                routed.confidence,
            )
            fallback_decision = RoutingDecision(
                target="qa",
                reason=f"Low routing confidence for '{routed.target}', defaulting to QA",
                deterministic=False,
                confidence=routed.confidence,
                source_filter=routed.source_filter,
            )
            return self._apply_document_hints(fallback_decision, question, extra_context, source_hints)
        return self._apply_document_hints(routed, question, extra_context, source_hints)

    async def _route_with_llm(
        self,
        question: str,
        extra_context: Optional[str],
        profile: Optional[LearnerProfile],
    ) -> RoutingDecision:
        if not self.routing_agent:
            return RoutingDecision(
                target="qa",
                reason="Routing agent unavailable; defaulting to QA",
                deterministic=False,
                confidence=0.0,
            )

        routing_prompt = self._build_routing_prompt(
            question=question,
            extra_context=extra_context,
            profile=profile,
        )
        session = self._get_routing_session()

        try:
            result = await Runner.run(self.routing_agent, input=routing_prompt, session=session)
        except Exception as exc:
            logger.error("[TutorAgent] Routing agent failed: %s", exc, exc_info=True)
            return RoutingDecision(
                target="qa",
                reason="Routing agent failure; default to QA",
                deterministic=False,
                confidence=0.0,
            )

        payload_text = result.final_output.strip() if result and result.final_output else ""
        decision = self._parse_routing_response(payload_text)
        if decision is None:
            logger.warning("[TutorAgent] Failed to parse routing response: %s", payload_text)
            return RoutingDecision(
                target="qa",
                reason="Routing response unreadable; default to QA",
                deterministic=False,
                confidence=0.0,
            )
        decision.deterministic = False
