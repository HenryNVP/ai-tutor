    async def _execute_decision(
        self,
        *,
        decision: RoutingDecision,
        prompt: str,
        session: SQLiteSession,
        on_delta: Optional[Callable[[str], None]],
    ) -> tuple[str, Optional[Quiz]]:
        if decision.target == "quiz":
            answer = await self._run_quiz_agent(prompt, session, on_delta)
            # quiz_agent will call generate_quiz tool and store result in self.state.last_quiz
            # The quiz will be picked up from state.last_quiz in answer_async if needed
            return answer, None

        if decision.target == "web":
            answer = await self._run_web_agent(prompt, session, on_delta)
            self.state.last_source = "web"
            return answer, None

        if decision.target == "ingestion":
            answer = await self._run_domain_agent(self.ingestion_agent, prompt, session, on_delta)
            return answer, None

        if decision.target == "note":
            answer, saved_file_path = await self._run_note_agent_with_file_detection(prompt, session, on_delta)
            if self.state.last_source is None:
                self.state.last_source = "notes"
            # Store saved file path in state for later retrieval
            self.state.saved_file_path = saved_file_path  # type: ignore
            return answer, None

        if decision.target == "visualization":
            answer = await self._run_visualization_agent(prompt, session, on_delta)
            if self.state.last_source is None:
                self.state.last_source = "visualization"
            return answer, None

        answer = await self._run_domain_agent(
            self.qa_agent,
            prompt,
            session,
            on_delta,
            allow_web_fallback=True,
        )
        return answer, None

    async def _run_domain_agent(
        self,
        agent: Agent | None,
        prompt: str,
        session: SQLiteSession,
        on_delta: Optional[Callable[[str], None]],
        *,
        allow_web_fallback: bool = False,
    ) -> str:
        if agent is None:
            return "I could not complete that request because the required agent is unavailable."
        logger.info("[TutorAgent] Running agent %s with prompt length %d", agent.name, len(prompt))
        try:
            result = await Runner.run(agent, input=prompt, session=session)
            logger.info(
                "[TutorAgent] Agent %s completed: output_length=%d",
                agent.name,
                len(result.final_output) if result and result.final_output else 0,
            )
        except Exception as exc:
            logger.error("[TutorAgent] Agent %s failed: %s", agent.name, exc, exc_info=True)
            return f"I encountered an error while delegating to {agent.name}: {exc}"

        text = result.final_output.strip() if result and result.final_output else ""
        if not text:
            logger.warning(
                "[TutorAgent] Agent %s returned empty output. Result: %s",
                agent.name,
                result,
            )
        if allow_web_fallback and self._should_web_fallback(text):
            logger.info("[TutorAgent] QA requested web fallback")
            return await self._run_web_agent(prompt, session, on_delta)

        if on_delta and text:
            for char in text:
                on_delta(char)

        if text:
            return text
        logger.warning("[TutorAgent] Agent %s produced no output, returning fallback message", agent.name)
        return "I could not generate a response. Please try rephrasing your request."

